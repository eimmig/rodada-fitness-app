package br.edu.utfpr.rodada.data

import android.annotation.SuppressLint
import android.content.Context
import androidx.activity.ComponentActivity
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import br.edu.utfpr.rodada.BuildConfig
import com.facebook.CallbackManager
import com.facebook.FacebookCallback
import com.facebook.FacebookException
import com.facebook.FacebookSdk
import com.facebook.login.LoginManager
import com.facebook.login.LoginResult
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.Firebase
import com.google.firebase.auth.AuthCredential
import com.google.firebase.auth.FacebookAuthProvider
import com.google.firebase.auth.FirebaseAuthException
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.auth.OAuthProvider
import com.google.firebase.auth.auth
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.suspendCancellableCoroutine
import kotlinx.coroutines.tasks.await
import kotlin.coroutines.resume
import kotlin.coroutines.resumeWithException

/**
 * Social sign-in through Firebase Auth.
 * - Google: Credential Manager, same flow as referencias/Login-PM46S-2025-1.
 * - Facebook: Facebook Login SDK gives an access token, exchanged for a Firebase credential.
 * - Microsoft: Firebase generic OAuth ("microsoft.com"), opened in a Custom Tab.
 */
class FirebaseAuthRepository(private val appContext: Context) : AuthRepository {
    private val auth = Firebase.auth
    private val _user = MutableStateFlow(auth.currentUser?.toUser())
    override val user: StateFlow<User?> = _user.asStateFlow()

    // Facebook needs an app id in local.properties; Microsoft and Google only need the Firebase console.
    override val providers = buildList {
        add(SignInProvider.GOOGLE)
        if (BuildConfig.HAS_FACEBOOK) add(SignInProvider.FACEBOOK)
        add(SignInProvider.MICROSOFT)
    }

    init {
        auth.addAuthStateListener { _user.value = it.currentUser?.toUser() }
    }

    override suspend fun signIn(provider: SignInProvider, activity: ComponentActivity): Result<User> = runCatching {
        val firebaseUser = when (provider) {
            SignInProvider.GOOGLE -> auth.signInWithCredential(googleCredential(activity)).await().user
            SignInProvider.FACEBOOK -> auth.signInWithCredential(facebookCredential(activity)).await().user
            SignInProvider.MICROSOFT -> microsoftSignIn(activity)
        } ?: error("Firebase did not return a user.")
        firebaseUser.toUser()
    }

    override fun signOut() {
        auth.signOut()
        if (BuildConfig.HAS_FACEBOOK && FacebookSdk.isInitialized()) LoginManager.getInstance().logOut()
    }

    // ---------- Google ----------

    private suspend fun googleCredential(activity: ComponentActivity): AuthCredential {
        val googleIdOption = GetGoogleIdOption.Builder()
            // Server (web) client ID, generated by the google-services plugin.
            .setServerClientId(webClientId())
            .setFilterByAuthorizedAccounts(false)
            .build()
        val request = GetCredentialRequest.Builder().addCredentialOption(googleIdOption).build()
        val result = try {
            CredentialManager.create(activity).getCredential(activity, request)
        } catch (e: GetCredentialCancellationException) {
            throw SignInCancelledException()
        }
        val credential = result.credential
        check(credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            "The returned credential is not a Google account."
        }
        val idToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
        return GoogleAuthProvider.getCredential(idToken, null)
    }

    // The resource only exists when google-services.json is present, so it is resolved at runtime.
    @SuppressLint("DiscouragedApi")
    private fun webClientId(): String {
        val id = appContext.resources.getIdentifier("default_web_client_id", "string", appContext.packageName)
        check(id != 0) { "default_web_client_id missing: check google-services.json." }
        return appContext.getString(id)
    }

    // ---------- Facebook ----------

    @Suppress("DEPRECATION") // sdkInitialize is the documented manual init when auto-init is off.
    private suspend fun facebookCredential(activity: ComponentActivity): AuthCredential {
        if (!FacebookSdk.isInitialized()) FacebookSdk.sdkInitialize(appContext)
        val manager = LoginManager.getInstance()
        val callbacks = CallbackManager.Factory.create()
        val token = try {
            suspendCancellableCoroutine { cont ->
                manager.registerCallback(callbacks, object : FacebookCallback<LoginResult> {
                    override fun onSuccess(result: LoginResult) = cont.resume(result.accessToken.token)
                    override fun onCancel() = cont.resumeWithException(SignInCancelledException())
                    override fun onError(error: FacebookException) = cont.resumeWithException(error)
                })
                manager.logIn(activity, callbacks, listOf("public_profile", "email"))
            }
        } finally {
            manager.unregisterCallback(callbacks)
        }
        return FacebookAuthProvider.getCredential(token)
    }

    // ---------- Microsoft ----------

    private suspend fun microsoftSignIn(activity: ComponentActivity): FirebaseUser? {
        // If the Activity was recreated while the Custom Tab was open, the result is waiting here.
        auth.pendingAuthResult?.let { return it.await().user }
        val provider = OAuthProvider.newBuilder("microsoft.com")
            .addCustomParameter("prompt", "select_account")
            .setScopes(listOf("openid", "profile", "email"))
            .build()
        return try {
            auth.startActivityForSignInWithProvider(activity, provider).await().user
        } catch (e: FirebaseAuthException) {
            if (e.errorCode == "ERROR_WEB_CONTEXT_CANCELED") throw SignInCancelledException() else throw e
        }
    }

    private fun FirebaseUser.toUser() = User(
        uid = uid,
        name = displayName?.takeIf { it.isNotBlank() }
            ?: providerData.firstNotNullOfOrNull { it.displayName?.takeIf(String::isNotBlank) }
            ?: email?.substringBefore('@')
            ?: "Sem nome",
        photoUrl = photoUrl?.toString(),
    )
}
